/**
 * Generates docs/ui/overlays.md from the source.
 *
 * Run: node scripts/overlay-inventory.mjs [--check]
 *
 * Generated rather than hand-written on purpose: a hand-maintained inventory of
 * 44 files goes stale on the first PR that adds a modal, and a stale inventory
 * is worse than none because it is trusted. `--check` fails when the committed
 * file no longer matches the tree, so CI notices before a reviewer has to.
 */

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, extname, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '../src');
const OUT = join(here, '../../docs/ui/overlays.md');

/**
 * How an overlay is recognised. Kept structural rather than name-based: a file
 * called *Modal.tsx may be a wrapper, while a page can inline a dialog without
 * saying so in its filename.
 */
const SIGNATURES = [
  { kind: 'modal/dialog', re: /role=["']dialog["']/ },
  { kind: 'modal/dialog', re: /fixed inset-0/ },
  { kind: 'drawer', re: /translate-x-full|drawer|Drawer/ },
  { kind: 'popover/menu', re: /role=["'](?:menu|listbox|tooltip)["']/ },
  { kind: 'toast', re: /react-hot-toast|Toaster|toast\./ },
];

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (extname(p) === '.tsx' && !p.includes('__tests__')) out.push(p);
  }
  return out;
}

const rows = [];
for (const file of walk(SRC)) {
  const src = readFileSync(file, 'utf8');
  const kinds = new Set();
  for (const { kind, re } of SIGNATURES) if (re.test(src)) kinds.add(kind);
  if (kinds.size === 0) continue;

  // Only count the signatures that make something an *overlay*; a page that
  // merely calls toast() is not one.
  const isOverlay = /role=["']dialog["']|fixed inset-0|role=["'](?:menu|listbox|tooltip)["']/.test(src);
  if (!isOverlay) continue;

  const raw = (
    src.match(
      /\b(?:bg|text|border|ring|divide|from|via|to)-(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose|white|black)(?:-\d{2,3})?\b/g,
    ) ?? []
  ).length;

  rows.push({
    path: relative(join(here, '../..'), file).replace(/\\/g, '/'),
    kinds: [...kinds].filter((k) => k !== 'toast').join(', ') || 'modal/dialog',
    raw,
  });
}

rows.sort((a, b) => a.path.localeCompare(b.path));

const clean = rows.filter((r) => r.raw === 0).length;
const body = `# Overlay inventory

<!-- GENERATED by frontend/scripts/overlay-inventory.mjs — do not edit by hand.
     Regenerate with: node scripts/overlay-inventory.mjs
     CI runs it with --check, so an unlisted overlay fails the build. -->

Every surface that renders above the page: modals, drawers, popovers, menus and
tooltips. These are where the "dark modal on a light app" bug lived, because an
overlay is the one place a developer is most tempted to hardcode a dark panel.

**Rule:** an overlay names roles, never colours — \`bg-surface-2\`,
\`text-fg-primary\`, \`border-border-default\`, and \`bg-surface-overlay\` for the
scrim. Raw palette classes are rejected by \`openrisk/no-raw-colors\`.

**Status:** ${clean}/${rows.length} overlays carry no raw colour.
The \`raw\` column counts remaining literal palette classes; anything above zero
is either a chart hue or a decorative gradient still awaiting a design decision
(the colour codemod declines to guess those).

| Overlay | Kind | raw |
|---|---|---|
${rows.map((r) => `| \`${r.path}\` | ${r.kinds} | ${r.raw || '—'} |`).join('\n')}

## Portals

The app renders overlays inline in the React tree rather than through
\`createPortal\`; a search for it returns nothing. They therefore inherit
\`[data-theme]\` from \`<html>\` automatically.

This is worth stating because the usual cause of an unthemed modal — a portal
mounted outside the themed subtree — does **not** apply here. Had the theme been
set on an application \`<div>\` it would, which is why \`uiStore.applyDom\` writes
to \`document.documentElement\` and must keep doing so. Any future portal into
\`document.body\` inherits correctly for the same reason.
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing file is a mismatch */
  }
  if (current.trim() !== body.trim()) {
    console.error(
      'docs/ui/overlays.md is out of date.\nRun: node scripts/overlay-inventory.mjs',
    );
    process.exit(1);
  }
  console.log(`overlay inventory up to date (${rows.length} overlays, ${clean} clean).`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT} — ${rows.length} overlays, ${clean} with no raw colour.`);
}
