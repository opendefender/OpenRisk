var semverPattern = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$`)

// ValidSemver reports whether v is MAJOR.MINOR.PATCH with no prefix, suffix or
// leading zeros.
func ValidSemver(v string) bool {
	return !strings.ContainsAny(v, "\n") && semverPattern.MatchString(v)
}
