// ChangelogEntry says what one content version of a catalogue changed (ADR 0013
// D3). Added, Changed and Retired list item keys, that is ReferenceCode as
// shipped, so an upgrade report can name the items a version touched.
type ChangelogEntry struct {
	Version string
	Date    string // ISO date, e.g. "2026-11-20"
	Summary string
	Added   []string
	Changed []string
	Retired []string
}

// contentRevision is the version and changelog of one catalogue.
type contentRevision struct {
	Version   string
	Changelog []ChangelogEntry
}

// initialContent is the first versioned revision every catalogue starts at.
func initialContent() contentRevision {
	return contentRevision{
		Version: "1.0.0",
		Changelog: []ChangelogEntry{
			{Version: "1.0.0", Date: "2026-11-20", Summary: "Initial versioned content"},
		},
	}
}

