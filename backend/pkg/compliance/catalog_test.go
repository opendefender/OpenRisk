// A catalog row lands in compliance_controls: reference_code varchar(50),
// name varchar(255), source_reference varchar(255). A longer value would fail
// the INSERT half-way through an import, so it fails here first.
func TestCatalogControls_FitTheirColumns(t *testing.T) {
	for key, cat := range catalogs {
		for _, c := range cat.Controls {
			if n := utf8.RuneCountInString(c.ReferenceCode); n > 50 {
				t.Errorf("%s %s: reference code is %d characters, column holds 50", key, c.ReferenceCode, n)
			}
			if n := utf8.RuneCountInString(c.Name); n > 255 {
				t.Errorf("%s %s: name is %d characters, column holds 255", key, c.ReferenceCode, n)
			}
			if n := utf8.RuneCountInString(c.SourceReference); n > 255 {
				t.Errorf("%s %s: source reference is %d characters, column holds 255", key, c.ReferenceCode, n)
			}
		}
		if n := utf8.RuneCountInString(cat.Version); n > 50 {
			t.Errorf("%s: version is %d characters, compliance_frameworks.version holds 50", key, n)
		}
	}
}

// The generated catalogs: every row keeps its official identifier, its text,
// and a link to the source it was generated from (#809 criteria 1-3 and 6).
func TestGeneratedCatalogs_CiteTheirSource(t *testing.T) {
	cases := []struct {
		key    string
		code   *regexp.Regexp
		source string
	}{
		{"nist-800-53-r5", regexp.MustCompile(`^[A-Z]{2}-\d+(\(\d+\))?$`), "https://raw.githubusercontent.com/usnistgov/oscal-content/"},
		{"nis2-2022-2555", regexp.MustCompile(`^(Art\.(20|21\([1-4a-j]\)|23\([1-4]\)(\([a-e]\))?)|RE2690-\d+\.\d+)$`), "https://eur-lex.europa.eu/eli/"},
		{"dora-2022-2554", regexp.MustCompile(`^Art\.\d+(\(\d+\))?$`), "https://eur-lex.europa.eu/eli/reg/2022/2554/oj"},
	}
	for _, tc := range cases {
		cat, ok := Get(tc.key)
		if !ok {
			t.Fatalf("%s not registered", tc.key)
		}
		for _, c := range cat.Controls {
			if !tc.code.MatchString(c.ReferenceCode) {
				t.Errorf("%s: %q is not an official identifier", tc.key, c.ReferenceCode)
			}
			if !strings.Contains(c.SourceReference, tc.source) {
				t.Errorf("%s %s: source %q does not link the official text", tc.key, c.ReferenceCode, c.SourceReference)
			}
			if strings.TrimSpace(c.Description) == "" {
				t.Errorf("%s %s: no text", tc.key, c.ReferenceCode)
			}
		}
	}
}

// NIS2 criterion 2: every measure of Art. 21(2)(a)-(j) and the reporting
// obligations of Art. 23 are rows, and the annex rows are present.
func TestNIS2_CoversArticle21And23AndTheAnnex(t *testing.T) {
	cat, _ := Get("nis2-2022-2555")
	have := map[string]bool{}
	annex := 0
	for _, c := range cat.Controls {
		have[c.ReferenceCode] = true
		if strings.HasPrefix(c.ReferenceCode, "RE2690-") {
			annex++
		}
	}
	for _, p := range "abcdefghij" {
		if code := "Art.21(" + string(p) + ")"; !have[code] {
			t.Errorf("missing %s", code)
		}
	}
	for _, code := range []string{"Art.23(1)", "Art.23(4)(a)", "Art.23(4)(b)", "Art.23(4)(d)"} {
		if !have[code] {
			t.Errorf("missing %s", code)
		}
	}
	// 13 measures, 53 sections in the annex of 2024/2690.
	if annex != 53 {
		t.Errorf("expected 53 annex sections, got %d", annex)
	}
}

// DORA criterion 3: each of Art. 5-30 has at least one row, except the
// articles addressed only to the ESAs and the authorities (15, 20, 21, 22),
// whose exclusion cmd/catalogsync records and checks paragraph by paragraph.
func TestDORA_CoversArticles5To30(t *testing.T) {
	cat, _ := Get("dora-2022-2554")
	arts := map[int]bool{}
	for _, c := range cat.Controls {
		var n int
		if _, err := fmt.Sscanf(c.ReferenceCode, "Art.%d", &n); err != nil {
			t.Fatalf("%q: %v", c.ReferenceCode, err)
		}
		arts[n] = true
	}
	authorityOnly := map[int]bool{15: true, 20: true, 21: true, 22: true}
	for n := 5; n <= 30; n++ {
		if arts[n] == authorityOnly[n] {
			t.Errorf("art. %d: row present = %v, but authority-only = %v", n, arts[n], authorityOnly[n])
		}
	}
}

