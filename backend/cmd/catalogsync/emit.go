package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// row is one catalogue control as it will be written.
type row struct {
	Code, Name, Description, Source string
}

// catalogFile is everything a generated catalog_*.go file states.
type catalogFile struct {
	Key, Name, Version, Description string
	VarName                         string
	// Provenance is the comment block: what the source is, which revision,
	// its hash, and why the content may be reproduced.
	Provenance []string
	Rows       []row
}

const header = `// Copyright (c) 2026 OpenDefender Contributors
// SPDX-License-Identifier: AGPL-3.0-only
// This program is free software: you can redistribute it and/or modify it under
// the terms of the GNU Affero General Public License v3.0 (see LICENSE).

// Code generated by cmd/catalogsync; DO NOT EDIT.
// Regenerate with: cd backend && go run ./cmd/catalogsync -catalog %s

package compliance

`

func (c catalogFile) render(job string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, header, job)
	for _, l := range c.Provenance {
		// Provenance lines are comments; some come from the downloaded source.
		// A line break would end the comment and turn the rest into Go code.
		if strings.ContainsAny(l, "\r\n") {
			return nil, fmt.Errorf("provenance line contains a line break: %q", l)
		}
		if l == "" {
			b.WriteString("//\n")
			continue
		}
		b.WriteString("// " + l + "\n")
	}
	b.WriteString("\nfunc init() {\n\tregister(Catalog{\n")
	fmt.Fprintf(&b, "\t\tKey: %q,\n\t\tName: %q,\n\t\tVersion: %q,\n\t\tDescription: %q,\n", c.Key, c.Name, c.Version, c.Description)
	fmt.Fprintf(&b, "\t\tAvailable: true,\n\t\tControls: %s,\n\t})\n}\n\n", c.VarName)
	fmt.Fprintf(&b, "var %s = []CatalogControl{\n", c.VarName)
	for _, r := range c.Rows {
		fmt.Fprintf(&b, "\t{%q, %q,\n\t\t%q,\n\t\t%q},\n", r.Code, r.Name, r.Description, r.Source)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// clean collapses whitespace the way a reader sees it.
func clean(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
